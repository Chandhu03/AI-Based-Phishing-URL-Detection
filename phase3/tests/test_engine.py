def test_model_identity_is_content_addressed():
    meta = {f: 1 for f in E.SCORING_FIELDS}
    mid, digest = E.model_identity(meta)
    assert mid == "url-host-" + digest[:16] and len(digest) == 64
    assert E.model_identity({**meta, "evaluation": {"x": 1}, "id": "other"}) == (mid, digest)
    assert E.model_identity({**meta, "intercept": 2})[0] != mid
    with pytest.raises(KeyError):
        E.model_identity({"format": "x"})


