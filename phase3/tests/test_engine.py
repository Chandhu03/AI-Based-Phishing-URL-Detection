TEXTS = ["example.com", "paypal.com.secure-login.xyz", "xn--pple-43d.com", "192.168.1.1", "::1",
         "a.b", "ab", "", "aaaa aaaa", "login-verify-account.co.uk", "bücher.de", "x" * 200]


def _coef(n=2**10, seed=1):
    return np.random.default_rng(seed).normal(0, 2, n)


def test_pure_scorer_matches_sklearn_hashing():
    coef = _coef()
    ref = E.logits(coef, 0.3, TEXTS)
    for t, r in zip(TEXTS, ref):
        assert abs(E.pure_logit(t, coef, 0.3) - r) <= 1e-9


def test_char_ngrams_match_sklearn_analyzer():
    analyzer = E.vectorizer(2**10).build_analyzer()
    for t in TEXTS:
        assert E.char_ngrams(t) == list(analyzer(t))


def test_short_text_scores_intercept_only():
    assert E.pure_logit("ab", _coef(), -1.25) == -1.25
    assert E.logits(_coef(), -1.25, ["ab"])[0] == -1.25


def test_bucket_handles_int32_min(monkeypatch):
    monkeypatch.setattr(E, "murmurhash3_32", lambda *a, **k: -(2**31))
    assert E.bucket("abc", 2**14) == (2**31 - 1 - (2**14 - 1)) % 2**14


@pytest.mark.parametrize("bits", [8, 16])
def test_quantize_round_trip_error_bound(bits):
    coef = _coef()
    q, scale = E.quantize(coef, bits)
    assert np.max(np.abs(E.dequantize(q, scale) - coef)) <= scale / 2 + 1e-12
    assert np.max(np.abs(q)) <= 2 ** (bits - 1) - 1


def test_platt_is_monotone_increasing():
    rng = np.random.default_rng(0)
    y = rng.integers(0, 2, 500)
    logit = y * 2.0 + rng.normal(0, 1, 500)
    a, b = E.fit_platt(logit, y)
    assert a > 0
    p = E.platt(np.sort(logit), a, b)
    assert np.all(np.diff(p) >= 0)


def test_thresholds_take_only_validation_arrays():
    assert list(inspect.signature(E.select_thresholds).parameters) == ["y_val", "p_val"]
    assert list(inspect.signature(E.fit_platt).parameters) == ["val_logit", "y_val"]
    y = np.array([0] * 100 + [1] * 100)
    p = np.r_[np.linspace(0, 0.6, 100), np.linspace(0.4, 1, 100)]
    t = E.select_thresholds(y, p)
    assert t["high"] >= t["elevated"]
    assert np.mean(p[y == 0] >= t["high"]) <= 0.01
    assert np.mean(p[y == 0] >= t["elevated"]) <= 0.05


def test_ece_perfect_and_worst():
    y = np.array([0, 1, 0, 1])
    assert E.ece(y, y.astype(float)) == 0.0
    assert E.ece(y, 1.0 - y) == 1.0


def _meta(coef, scale, q):
    return {"format": E.FORMAT, "id": "test", "intercept": 0.1, "coefScale": scale,
            "coefBase64": base64.b64encode(q.astype("<i2").tobytes()).decode(),
            "calibration": {"kind": "platt", "a": 1.0, "b": 0.0}}


def test_export_refuses_on_parity_failure(tmp_path, monkeypatch):
    q, s = E.quantize(_coef(), 16)
    monkeypatch.setattr(E, "pure_logit", lambda t, c, i: 999.0)
    js, golden = tmp_path / "m.js", tmp_path / "g.json"
    with pytest.raises(E.ParityError):
        E.export(_meta(E.dequantize(q, s), s, q), E.dequantize(q, s), js, golden)
    assert not js.exists() and not golden.exists()


def test_export_writes_module_and_golden_schema(tmp_path):
    q, s = E.quantize(_coef(), 16)
    coef = E.dequantize(q, s)
    js, golden = tmp_path / "m.js", tmp_path / "g.json"
    info = E.export(_meta(coef, s, q), coef, js, golden)
    assert info["golden_vectors"] >= 300
    text = js.read_text(encoding="utf-8")
    assert text.startswith("// GENERATED by phase3 engine export - do not edit.")
    assert "export const MODEL = {" in text
    g = json.loads(golden.read_text(encoding="utf-8"))
    assert g["model_id"] == "test"
    for v in g["vectors"]:
        assert set(v) == {"url", "text", "logit", "probability"}
        assert 0.0 < v["probability"] < 1.0
        assert abs(E.pure_logit(v["text"], coef, 0.1) - v["logit"]) <= 1e-9


