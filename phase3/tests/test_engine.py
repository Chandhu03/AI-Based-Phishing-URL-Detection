def test_site_evaluation_counts_each_host_and_domain_once():
    # 10 URLs on one phishing host (caught), 1 URL on another (missed), 2 legitimate hosts.
    texts = ["bad.example"] * 10 + ["sly.example", "ok.example", "fine.test"]
    groups = ["bad.example"] * 10 + ["sly.example", "ok.example", "fine.test"]
    y = np.array([1] * 11 + [0, 0])
    s = np.array([0.99] * 10 + [0.10, 0.05, 0.20])
    r = E.site_evaluation(texts, groups, y, s, {"high": 0.9})
    assert r["per_url"]["at_high"]["recall"] == 10 / 11
    assert r["per_host"]["n"] == 4 and r["per_host"]["at_high"]["recall"] == 0.5
    assert r["per_domain"]["n"] == 4
    assert abs(r["largest_domain_share"] - 10 / 13) < 1e-12


